/**
 * Package B, Gate 11 — bounded, read-only editorial/campaign opportunity source seam.
 *
 * Reconciliation finding: no structured editorial/campaign metadata source exists today.
 * app/lib/magazine/** models published magazine ISSUES (month/cover/PDF/flipbook) — it has no
 * per-article theme/category/audience/sponsorship-eligibility metadata that a match engine could
 * use, and adapting it would misuse issue-level data for article-level matching. Building a full
 * editorial calendar CMS inside Business Concierge is explicitly out of scope for Package B.
 *
 * This file is the smallest workable seam: a typed interface plus a small, code-reviewed starter
 * registry of category/theme-based opportunity candidates (never customer-specific names — see
 * doctrine below). If a real structured editorial/campaign data source is built later (by the
 * magazine team or a future package), only `listActiveEditorialOpportunitySources()` needs to
 * change — the match engine and everything downstream is unaffected.
 */
