import type { OpportunitySourceType, OpportunityType } from "./types";

export interface EditorialOpportunitySource {
  key: string;
  titleEs: string;
  titleEn: string;
  themeEs: string;
  themeEn: string;
  sourceType: OpportunitySourceType;
  opportunityType: OpportunityType;
  creativeFamily: CreativeFamily;
  /** Category-based matching only — never a specific business/customer. */
  suggestedBusinessCategories: readonly BroadBusinessType[];
  /** Optional service-area city hints. Empty means "no geography constraint". */
  suggestedCities: readonly string[];
  /** ISO date window this opportunity is active for. Null = evergreen/no fixed window. */
  activeFrom: string | null;
  activeUntil: string | null;
  /** True only for content families where a paid sponsorship relationship is a plausible outcome. */
  sponsorshipEligible: boolean;
}

