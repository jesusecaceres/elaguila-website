/**
 * Read-only accessor. Filters out sources whose active window has already closed — an evergreen
 * source (activeFrom/activeUntil both null) is always considered active.
 */
export function listActiveEditorialOpportunitySources(nowIso: string = new Date().toISOString()): readonly EditorialOpportunitySource[] {
  const now = new Date(nowIso).getTime();
  return EDITORIAL_OPPORTUNITY_REGISTRY.filter((source) => {
    if (source.activeFrom && new Date(source.activeFrom).getTime() > now) return false;
    if (source.activeUntil && new Date(source.activeUntil).getTime() < now) return false;
    return true;
  });
}
